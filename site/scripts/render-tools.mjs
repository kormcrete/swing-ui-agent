// Renders src/data/tools.json (the agent's own tool schemas, from `tools/list`) into the Tools reference page.
// The deploy job refreshes tools.json from the running demo app; the committed copy lets the site build without it.
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../src/data/tools.json', import.meta.url);
const target = new URL('../src/content/docs/reference/tools.md', import.meta.url);
const { tools } = JSON.parse(readFileSync(source, 'utf8'));

const text = (value) => String(value ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const cell = (value) => text(value).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

function typeOf(schema) {
	if (!schema) return '';
	if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(' · ');
	if (schema.type === 'array') return `array of ${typeOf(schema.items) || 'any'}`;
	return schema.type ?? (schema.oneOf || schema.anyOf ? 'one of several' : 'any');
}

function section(tool) {
	const schema = tool.inputSchema ?? {};
	const required = new Set(schema.required ?? []);
	const props = Object.entries(schema.properties ?? {});
	const kind = tool.annotations?.readOnlyHint ? 'Read-only.' : 'Acts on the app.';
	const lines = [`## ${tool.name}`, '', `*${kind}*`, '', text(tool.description), ''];
	if (props.length) {
		lines.push('| Parameter | Type | Required | Description |', '| --- | --- | --- | --- |');
		for (const [name, p] of props) {
			lines.push(`| \`${name}\` | ${cell(typeOf(p))} | ${required.has(name) ? 'yes' : ''} | ${cell(p.description)} |`);
		}
		lines.push('');
	} else {
		lines.push('No parameters.', '');
	}
	return lines.join('\n');
}

const page = [
	'---',
	'title: Tools',
	'description: Every tool the agent offers, with its parameters. Generated from the agent\'s own schemas.',
	'sidebar:',
	'  order: 1',
	'editUrl: false',
	'---',
	'',
	'<!-- Generated by scripts/render-tools.mjs from src/data/tools.json. Do not edit. -->',
	'',
	'The same tools are offered over MCP and through the [CLI](/swing-ui-agent/reference/cli/). This page is generated from the schemas the agent itself reports (`tools/list`), captured from version 0.1.0-SNAPSHOT. For the schema of the version you run, ask the running agent: `java -jar <agent jar> tools <tool>`.',
	'',
	...tools.map(section),
].join('\n');

writeFileSync(target, page);
console.log(`render-tools: ${tools.length} tools → ${target.pathname}`);
